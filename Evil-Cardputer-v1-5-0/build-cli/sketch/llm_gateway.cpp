static void llmGWChatLoop() {
    std::vector<String> chatLines;
    int scrollOffset = 0;
    bool needRedraw = true;

    chatLines.push_back("=== LLM Gateway Chat ===");
    chatLines.push_back("Model: " + String(llmGWSession.currentModel));
    chatLines.push_back("");
    chatLines.push_back("Type message, Enter to send");
    chatLines.push_back("Backspace to exit");
    chatLines.push_back("------------------------");

    while (true) {
        // Draw chat history
        if (needRedraw) {
            LB::clear();

            int startLine = max(0, (int)chatLines.size() - LLM_GW_LINES_PER_PAGE + scrollOffset);
            for (int i = 0; i < LLM_GW_LINES_PER_PAGE && (startLine + i) < chatLines.size(); i++) {
                LB::setCursor(2, 2 + i * LLM_GW_LINE_HEIGHT);
                String line = chatLines[startLine + i];
                if (line.length() > LLM_GW_CHARS_PER_LINE) {
                    line = line.substring(0, LLM_GW_CHARS_PER_LINE);
                }
                LB::print(line);
            }
            needRedraw = false;
        }

        // Show prompt
        llmGWDrawChatPrompt("> ", TFT_GREEN);

        // Handle keyboard input first
        M5.update();
        M5Cardputer.update();

        if (M5Cardputer.Keyboard.isKeyPressed(KEY_BACKSPACE)) {
            delay(200);
            break;
        }

        if (M5Cardputer.Keyboard.isKeyPressed(';') && scrollOffset < 0) {
            scrollOffset++;
            needRedraw = true;
            delay(150);
            continue;
        } else if (M5Cardputer.Keyboard.isKeyPressed('.') && scrollOffset > -(int)chatLines.size() + LLM_GW_LINES_PER_PAGE) {
            scrollOffset--;
            needRedraw = true;
            delay(150);
            continue;
        }

        // Get user input
        String userInput = getUserInput(false);

        if (userInput.length() == 0) {
            delay(100);
            continue;
        }

        // Add user message to display
        chatLines.push_back("");
        std::vector<String> userLines;
        wrapText("You: " + userInput, userLines, LLM_GW_CHARS_PER_LINE);
        for (const String& line : userLines) {
            chatLines.push_back(line);
        }
        scrollOffset = 0;
        needRedraw = true;

        // Draw status
        llmGWDrawChatPrompt("Thinking...", TFT_YELLOW);

        // Send message
        String response;
        LLMGWError err = llmGWSendMessage(userInput.c_str(), response);

        if (err != LLM_GW_OK) {
            if (err == LLM_GW_ERR_SESSION_EXPIRED && llmGWConfig.autoReconnect) {
                // Try to re-authenticate
                err = llmGWAuthenticate();
                if (err == LLM_GW_OK) {
                    err = llmGWStartChat(llmGWSession.currentModel);
                    if (err == LLM_GW_OK) {
                        err = llmGWSendMessage(userInput.c_str(), response);
                    }
                }
            }

            if (err != LLM_GW_OK) {
                chatLines.push_back("");
                chatLines.push_back("Error: " + String(llmGWErrorToString(err)));
                needRedraw = true;
                continue;
            }
        }

        // Add assistant response
        chatLines.push_back("");
        std::vector<String> responseLines;
        wrapText("AI: " + response, responseLines, LLM_GW_CHARS_PER_LINE);
        for (const String& line : responseLines) {
            chatLines.push_back(line);
        }
        needRedraw = true;
    }

    llmGWStopChat();
}

// ============================================================================
// Disconnect
// ============================================================================

static void llmGWDisconnect() {
    llmGWStopChat();
    llmGWSession.sessionToken[0] = '\0';
    llmGWSession.tokenExpiresAt = 0;
    llmGWSession.state = LLM_GW_STATE_DISCONNECTED;
    llmGWSession.client.stop();
}

// ============================================================================
// Error/State strings
// ============================================================================

const char* llmGWErrorToString(LLMGWError err) {
    switch (err) {
        case LLM_GW_OK:                     return "OK";
        case LLM_GW_ERR_NO_WIFI:            return "No WiFi";
        case LLM_GW_ERR_NO_SERVER:          return "Server not found";
        case LLM_GW_ERR_CONNECT_FAILED:     return "Connection failed";
        case LLM_GW_ERR_HTTP_ERROR:         return "HTTP error";
        case LLM_GW_ERR_AUTH_FAILED:        return "Auth failed";
        case LLM_GW_ERR_SIGNATURE_FAILED:   return "Signature failed";
        case LLM_GW_ERR_SESSION_EXPIRED:    return "Session expired";
        case LLM_GW_ERR_CHAT_FAILED:        return "Chat failed";
        case LLM_GW_ERR_TIMEOUT:            return "Timeout";
        case LLM_GW_ERR_PARSE_ERROR:        return "Parse error";
        case LLM_GW_ERR_NO_KEYS:            return "Keys not found";
        case LLM_GW_ERR_USER_CANCEL:        return "Cancelled";
        case LLM_GW_ERR_OLLAMA_UNAVAILABLE: return "Ollama unavailable";
        case LLM_GW_ERR_MODEL_NOT_FOUND:    return "Model not found";
        default:                            return "Unknown error";
    }
}

const char* llmGWStateToString(LLMGWState state) {
    switch (state) {
        case LLM_GW_STATE_DISCONNECTED:     return "Disconnected";
        case LLM_GW_STATE_CONNECTING:       return "Connecting";
        case LLM_GW_STATE_AUTHENTICATING:   return "Authenticating";
        case LLM_GW_STATE_READY:            return "Ready";
        case LLM_GW_STATE_CHATTING:         return "Chatting";
        case LLM_GW_STATE_ERROR:            return "Error";
        default:                            return "Unknown";
    }
}

// ============================================================================
// Main Entry Point
// ============================================================================

void llmGatewayChat() {
    // Check WiFi
    if (WiFi.status() != WL_CONNECTED) {
        waitAndReturnToMenu("Not connected to WiFi");
        return;
    }

    inMenu = false;

    // Load config
    llmGWLoadConfig();

    // Initialize RNG
    mbedtls_entropy_init(&llmGWSession.entropy);
    mbedtls_ctr_drbg_init(&llmGWSession.ctr_drbg);
    const char* pers = "llmgw_session";
    mbedtls_ctr_drbg_seed(&llmGWSession.ctr_drbg, mbedtls_entropy_func,
                          &llmGWSession.entropy, (const uint8_t*)pers, strlen(pers));

    // Check if RDP keys exist (LLM Gateway uses same keys as Remote Desktop)
    if (!llmGWKeysExist()) {
        llmGWDrawStatus("No RDP keys found!", "Use Remote Desktop first");
        delay(2000);
        waitAndReturnToMenu("Generate keys via RDP");
        return;
    }

    // Load keys
    if (!llmGWLoadKeys()) {
        waitAndReturnToMenu("Failed to load keys");
        return;
    }

    // Get server address if not configured
    if (strlen(llmGWConfig.serverHost) == 0) {
        llmGWPromptScreen("Enter Gateway IP:");
        String host = getUserInput(false);
        if (host.length() == 0) {
            waitAndReturnToMenu("Cancelled");
            return;
        }
        strlcpy(llmGWConfig.serverHost, host.c_str(), sizeof(llmGWConfig.serverHost));
        llmGWSaveConfig();
    }

    // Authenticate
    llmGWDrawStatus("Connecting to", llmGWConfig.serverHost);
    LLMGWError err = llmGWAuthenticate();
    if (err != LLM_GW_OK) {
        llmGWShowError(err);
        llmGWDisconnect();
        inMenu = true;
        return;
    }

    // Fetch models
    err = llmGWFetchModels();
    if (err != LLM_GW_OK) {
        llmGWShowError(err);
        llmGWDisconnect();
        inMenu = true;
        return;
    }

    if (llmGWSession.models.empty()) {
        waitAndReturnToMenu("No models available");
        llmGWDisconnect();
        return;
    }

    // Select model
    int modelIdx = llmGWSelectModel();
    if (modelIdx < 0) {
        llmGWDisconnect();
        inMenu = true;
        return;
    }

    const char* selectedModel = llmGWSession.models[modelIdx].c_str();

    // Start chat session
    err = llmGWStartChat(selectedModel);
    if (err != LLM_GW_OK) {
        llmGWShowError(err);
        llmGWDisconnect();
        inMenu = true;
        return;
    }

    // Run chat loop
    llmGWChatLoop();

    // Cleanup
    llmGWDisconnect();
    mbedtls_entropy_free(&llmGWSession.entropy);
    mbedtls_ctr_drbg_free(&llmGWSession.ctr_drbg);

    inMenu = true;
}
