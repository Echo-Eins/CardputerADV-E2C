static String llmGWHttpRequest(const char* method, const char* path, const String& body, int& httpCode) {
    httpCode = 0;

    if (!llmGWSession.client.connect(llmGWConfig.serverHost, llmGWConfig.serverPort)) {
        Serial.println("[LLMGW] Connection failed");
        return "";
    }

    // Build request
    String request = String(method) + " " + path + " HTTP/1.1\r\n";
    request += "Host: " + String(llmGWConfig.serverHost) + "\r\n";
    request += "Content-Type: application/json\r\n";

    // Add auth header if we have a token
    if (strlen(llmGWSession.sessionToken) > 0) {
        request += "Authorization: Bearer " + String(llmGWSession.sessionToken) + "\r\n";
    }

    if (body.length() > 0) {
        request += "Content-Length: " + String(body.length()) + "\r\n";
    }
    request += "Connection: close\r\n\r\n";

    if (body.length() > 0) {
        request += body;
    }

    llmGWSession.client.print(request);
    llmGWSession.client.setTimeout(LLM_GW_HTTP_TIMEOUT_MS);

    // Read response status line
    String statusLine = llmGWSession.client.readStringUntil('\n');
    if (statusLine.startsWith("HTTP/1.")) {
        int spacePos = statusLine.indexOf(' ');
        if (spacePos > 0) {
            httpCode = statusLine.substring(spacePos + 1, spacePos + 4).toInt();
        }
    }

    // Skip headers
    while (llmGWSession.client.connected()) {
        String line = llmGWSession.client.readStringUntil('\n');
        if (line == "\r" || line.length() == 0) break;
    }

    // Read body
    String responseBody = "";
    while (llmGWSession.client.available()) {
        responseBody += llmGWSession.client.readString();
    }

    llmGWSession.client.stop();

    return responseBody;
}

