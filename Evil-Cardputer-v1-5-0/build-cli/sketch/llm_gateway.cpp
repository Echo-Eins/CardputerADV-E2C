// Key generation removed - LLM Gateway uses same keys as Remote Desktop
// Keys are generated by RDP and stored in /rd_keys/

bool llmGWLoadKeys() {
    if (llmGWKeys.loaded) return true;

    mbedtls_ecp_keypair_init(&llmGWKeys.ecdsaKey);
    mbedtls_ecp_point_init(&llmGWKeys.serverPubPoint);

    // Load private key
    File f = SD.open(LLM_GW_PRIVKEY_PATH, FILE_READ);
    if (!f || f.size() != LLM_GW_ECDSA_PRIVKEY_SIZE) {
        Serial.println("[LLMGW] Failed to read private key");
        if (f) f.close();
        return false;
    }
    f.read(llmGWKeys.privateKey, LLM_GW_ECDSA_PRIVKEY_SIZE);
    f.close();

    // Load public key
    f = SD.open(LLM_GW_PUBKEY_PATH, FILE_READ);
    if (!f || f.size() != LLM_GW_ECDSA_PUBKEY_SIZE) {
        Serial.println("[LLMGW] Failed to read public key");
        if (f) f.close();
        return false;
    }
    f.read(llmGWKeys.publicKey, LLM_GW_ECDSA_PUBKEY_SIZE);
    f.close();

    // Load server public key if exists (65 bytes uncompressed, same as RDP)
    if (SD.exists(LLM_GW_SERVER_PUBKEY_PATH)) {
        f = SD.open(LLM_GW_SERVER_PUBKEY_PATH, FILE_READ);
        if (f && f.size() == LLM_GW_ECDSA_PUBKEY_SIZE) {
            f.read(llmGWKeys.serverPublicKey, LLM_GW_ECDSA_PUBKEY_SIZE);
            f.close();
            Serial.println("[LLMGW] Server public key loaded from file");
        } else {
            if (f) f.close();
            Serial.println("[LLMGW] Server public key not found or wrong size");
        }
    }

    // Setup ECDSA keypair
    int ret = mbedtls_ecp_group_load(&llmGWKeys.ecdsaKey.MBEDTLS_PRIVATE(grp), MBEDTLS_ECP_DP_SECP256R1);
    if (ret != 0) {
        Serial.printf("[LLMGW] ECP group load failed: -0x%04X\n", -ret);
        return false;
    }

    ret = mbedtls_mpi_read_binary(&llmGWKeys.ecdsaKey.MBEDTLS_PRIVATE(d),
                                   llmGWKeys.privateKey, LLM_GW_ECDSA_PRIVKEY_SIZE);
    if (ret != 0) {
        Serial.printf("[LLMGW] Import private key failed: -0x%04X\n", -ret);
        return false;
    }

    ret = mbedtls_ecp_point_read_binary(&llmGWKeys.ecdsaKey.MBEDTLS_PRIVATE(grp),
                                         &llmGWKeys.ecdsaKey.MBEDTLS_PRIVATE(Q),
                                         llmGWKeys.publicKey, LLM_GW_ECDSA_PUBKEY_SIZE);
    if (ret != 0) {
        Serial.printf("[LLMGW] Import public key failed: -0x%04X\n", -ret);
        return false;
    }

    ret = mbedtls_ecp_check_pub_priv(&llmGWKeys.ecdsaKey, &llmGWKeys.ecdsaKey,
                                     mbedtls_ctr_drbg_random, &llmGWSession.ctr_drbg);
    if (ret != 0) {
        Serial.printf("[LLMGW] Keypair validation failed: -0x%04X\n", -ret);
        return false;
    }

    llmGWKeys.loaded = true;
    Serial.println("[LLMGW] Keys loaded successfully");
    return true;
}

// ============================================================================
// ECDSA Signing
// ============================================================================

static bool llmGWSign(const uint8_t* data, size_t dataLen, uint8_t* signature) {
    if (!llmGWKeys.loaded) return false;

    // Hash the data (ECDSA signs SHA256 hash)
    uint8_t hash[32];
    mbedtls_sha256(data, dataLen, hash, 0);

    mbedtls_mpi r, s;
    mbedtls_mpi_init(&r);
    mbedtls_mpi_init(&s);

    int ret = mbedtls_ecdsa_sign(&llmGWKeys.ecdsaKey.MBEDTLS_PRIVATE(grp), &r, &s,
                                  &llmGWKeys.ecdsaKey.MBEDTLS_PRIVATE(d),
                                  hash, sizeof(hash),
                                  mbedtls_ctr_drbg_random, &llmGWSession.ctr_drbg);
    if (ret != 0) {
        Serial.printf("[LLMGW] ECDSA sign failed: -0x%04X\n", -ret);
        mbedtls_mpi_free(&r);
        mbedtls_mpi_free(&s);
        return false;
    }

    // Export r || s (32 + 32 bytes)
    ret = mbedtls_mpi_write_binary(&r, signature, 32);
    if (ret != 0) {
        mbedtls_mpi_free(&r);
        mbedtls_mpi_free(&s);
        return false;
    }

    ret = mbedtls_mpi_write_binary(&s, signature + 32, 32);
    mbedtls_mpi_free(&r);
    mbedtls_mpi_free(&s);

    return ret == 0;
}

