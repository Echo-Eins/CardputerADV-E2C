static int llmGWSelectModel() {
    if (llmGWSession.models.empty()) {
        return -1;
    }

    int selected = 0;
    int offset = 0;
    const int maxVisible = 8;

    while (true) {
        LB::clear();
        LB::setTextSize(1);
        LB::setCursor(5, 5);
        LB::setTextColor(TFT_CYAN);
        LB::println("Select Model (;/. to scroll)");
        LB::setTextColor(TFT_WHITE);

        for (int i = 0; i < maxVisible && (offset + i) < llmGWSession.models.size(); i++) {
            int idx = offset + i;
            LB::setCursor(5, 20 + i * 13);

            LB::setTextColor(idx == selected ? TFT_GREEN : TFT_WHITE);
            LB::print(idx == selected ? "> " : "  ");

            String modelName = llmGWSession.models[idx];
            if (modelName.length() > 32) {
                modelName = modelName.substring(0, 29) + "...";
            }
            LB::println(modelName);
        }

        LB::setTextColor(TFT_DARKGREY);
        LB::setCursor(5, 125);
        LB::printf("%d/%d  [Enter]=Select [Esc]=Back",
                          selected + 1, llmGWSession.models.size());
        LB::setTextColor(TFT_WHITE);

        // Wait for input
        while (true) {
            M5.update();
            M5Cardputer.update();

            if (M5Cardputer.Keyboard.isKeyPressed(KEY_BACKSPACE)) {
                delay(200);
                return -1;  // Cancel
            }

            if (M5Cardputer.Keyboard.isKeyPressed(KEY_ENTER)) {
                delay(200);
                return selected;
            }

            if (M5Cardputer.Keyboard.isKeyPressed(';')) {
                if (selected > 0) {
                    selected--;
                    if (selected < offset) offset = selected;
                }
                delay(150);
                break;
            }

            if (M5Cardputer.Keyboard.isKeyPressed('.')) {
                if (selected < llmGWSession.models.size() - 1) {
                    selected++;
                    if (selected >= offset + maxVisible) offset = selected - maxVisible + 1;
                }
                delay(150);
                break;
            }

            delay(30);
        }
    }
}

// ============================================================================
// Word wrapping utility
// ============================================================================

static void wrapText(const String& text, std::vector<String>& lines, int maxChars) {
    String currentLine = "";
    String word = "";

    for (int i = 0; i <= text.length(); i++) {
        char c = (i < text.length()) ? text[i] : ' ';

        if (c == ' ' || c == '\n' || i == text.length()) {
            if (word.length() > 0) {
                if (currentLine.length() + word.length() + 1 > maxChars) {
                    if (currentLine.length() > 0) {
                        lines.push_back(currentLine);
                        currentLine = "";
                    }
                }

                if (currentLine.length() > 0) currentLine += " ";
                currentLine += word;
                word = "";
            }

            if (c == '\n') {
                lines.push_back(currentLine);
                currentLine = "";
            }
        } else {
            word += c;
        }
    }

    if (currentLine.length() > 0) {
        lines.push_back(currentLine);
    }
}

