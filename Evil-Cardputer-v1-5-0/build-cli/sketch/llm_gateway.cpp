void llmGWLoadConfig() {
    if (!SD.exists(LLM_GW_CONFIG_PATH)) return;

    File f = SD.open(LLM_GW_CONFIG_PATH, FILE_READ);
    if (!f) return;

    StaticJsonDocument<256> doc;
    if (deserializeJson(doc, f) == DeserializationError::Ok) {
        strlcpy(llmGWConfig.serverHost, doc["host"] | "", sizeof(llmGWConfig.serverHost));
        llmGWConfig.serverPort = doc["port"] | LLM_GW_DEFAULT_PORT;
        strlcpy(llmGWConfig.selectedModel, doc["model"] | "", sizeof(llmGWConfig.selectedModel));
        llmGWConfig.autoReconnect = doc["autoReconnect"] | true;
    }
    f.close();
}

