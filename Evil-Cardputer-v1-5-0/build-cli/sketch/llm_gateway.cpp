static LLMGWError llmGWFetchModels() {
    llmGWDrawStatus("Fetching models...");

    int httpCode;
    String response = llmGWHttpRequest("GET", "/models?type=local", "", httpCode);

    if (httpCode == 401) {
        return LLM_GW_ERR_SESSION_EXPIRED;
    }

    if (httpCode != 200) {
        Serial.printf("[LLMGW] Fetch models failed: HTTP %d\n", httpCode);
        return LLM_GW_ERR_HTTP_ERROR;
    }

    StaticJsonDocument<2048> doc;
    if (deserializeJson(doc, response) != DeserializationError::Ok) {
        return LLM_GW_ERR_PARSE_ERROR;
    }

    llmGWSession.models.clear();
    JsonArray models = doc["models"].as<JsonArray>();
    for (JsonObject model : models) {
        const char* name = model["name"];
        if (name) {
            llmGWSession.models.push_back(String(name));
        }
    }

    Serial.printf("[LLMGW] Found %d models\n", llmGWSession.models.size());
    return LLM_GW_OK;
}

