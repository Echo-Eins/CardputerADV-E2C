static LLMGWError llmGWAuthenticate() {
    llmGWSession.state = LLM_GW_STATE_AUTHENTICATING;
    llmGWDrawStatus("Authenticating...");

    // Step 1: Get challenge
    char pubKeyHex[LLM_GW_ECDSA_PUBKEY_SIZE * 2 + 1];
    bytesToHex(llmGWKeys.publicKey, LLM_GW_ECDSA_PUBKEY_SIZE, pubKeyHex);

    StaticJsonDocument<256> challengeReq;
    challengeReq["client_public_key"] = pubKeyHex;
    String reqBody;
    serializeJson(challengeReq, reqBody);

    int httpCode;
    String response = llmGWHttpRequest("POST", "/auth/challenge", reqBody, httpCode);

    if (httpCode != 200) {
        Serial.printf("[LLMGW] Challenge failed: HTTP %d\n", httpCode);
        return LLM_GW_ERR_AUTH_FAILED;
    }

    StaticJsonDocument<512> challengeResp;
    if (deserializeJson(challengeResp, response) != DeserializationError::Ok) {
        Serial.println("[LLMGW] Failed to parse challenge response");
        return LLM_GW_ERR_PARSE_ERROR;
    }

    const char* challengeHex = challengeResp["challenge"];
    uint64_t timestamp = challengeResp["timestamp"];
    const char* nonceHex = challengeResp["nonce"];
    const char* serverSigHex = challengeResp["server_signature"];

    if (!challengeHex || !nonceHex || !serverSigHex) {
        Serial.println("[LLMGW] Missing fields in challenge response");
        return LLM_GW_ERR_PARSE_ERROR;
    }

    // Decode challenge
    uint8_t challenge[LLM_GW_CHALLENGE_SIZE];
    if (!hexToBytes(challengeHex, challenge, sizeof(challenge))) {
        return LLM_GW_ERR_PARSE_ERROR;
    }

    // Step 2: Sign the challenge hash
    uint8_t clientSig[LLM_GW_ECDSA_SIG_SIZE];
    if (!llmGWSign(challenge, LLM_GW_CHALLENGE_SIZE, clientSig)) {
        return LLM_GW_ERR_SIGNATURE_FAILED;
    }

    char clientSigHex[LLM_GW_ECDSA_SIG_SIZE * 2 + 1];
    bytesToHex(clientSig, LLM_GW_ECDSA_SIG_SIZE, clientSigHex);

    // Step 3: Verify signature
    StaticJsonDocument<256> verifyReq;
    verifyReq["nonce"] = nonceHex;
    verifyReq["client_signature"] = clientSigHex;
    String verifyBody;
    serializeJson(verifyReq, verifyBody);

    response = llmGWHttpRequest("POST", "/auth/verify", verifyBody, httpCode);

    if (httpCode != 200) {
        Serial.printf("[LLMGW] Verify failed: HTTP %d\n", httpCode);
        return LLM_GW_ERR_AUTH_FAILED;
    }

    StaticJsonDocument<256> verifyResp;
    if (deserializeJson(verifyResp, response) != DeserializationError::Ok) {
        return LLM_GW_ERR_PARSE_ERROR;
    }

    const char* token = verifyResp["session_token"];
    uint64_t expiresAt = verifyResp["expires_at"];

    if (!token) {
        return LLM_GW_ERR_AUTH_FAILED;
    }

    strlcpy(llmGWSession.sessionToken, token, sizeof(llmGWSession.sessionToken));
    llmGWSession.tokenExpiresAt = expiresAt;
    llmGWSession.state = LLM_GW_STATE_READY;

    Serial.printf("[LLMGW] Authenticated, token expires at %llu\n", expiresAt);
    return LLM_GW_OK;
}

