static LLMGWError llmGWStartChat(const char* model) {
    llmGWDrawStatus("Starting chat...", model);

    StaticJsonDocument<128> req;
    req["model"] = model;
    String body;
    serializeJson(req, body);

    int httpCode;
    String response = llmGWHttpRequest("POST", "/chat/start", body, httpCode);

    if (httpCode == 401) {
        return LLM_GW_ERR_SESSION_EXPIRED;
    }

    if (httpCode != 200) {
        Serial.printf("[LLMGW] Start chat failed: HTTP %d\n", httpCode);
        return LLM_GW_ERR_CHAT_FAILED;
    }

    StaticJsonDocument<256> doc;
    if (deserializeJson(doc, response) != DeserializationError::Ok) {
        return LLM_GW_ERR_PARSE_ERROR;
    }

    const char* sessionId = doc["session_id"];
    if (!sessionId) {
        return LLM_GW_ERR_CHAT_FAILED;
    }

    strlcpy(llmGWSession.chatSessionId, sessionId, sizeof(llmGWSession.chatSessionId));
    strlcpy(llmGWSession.currentModel, model, sizeof(llmGWSession.currentModel));
    llmGWSession.state = LLM_GW_STATE_CHATTING;

    Serial.printf("[LLMGW] Chat started: %s\n", sessionId);
    return LLM_GW_OK;
}

static LLMGWError llmGWSendMessage(const char* message, String& response) {
    StaticJsonDocument<4096> req;
    req["session_id"] = llmGWSession.chatSessionId;
    req["message"] = message;
    String body;
    serializeJson(req, body);

    // Use longer timeout for LLM response
    llmGWSession.client.setTimeout(LLM_GW_CHAT_TIMEOUT_MS);

    int httpCode;
    String resp = llmGWHttpRequest("POST", "/chat/send", body, httpCode);

    if (httpCode == 401) {
        return LLM_GW_ERR_SESSION_EXPIRED;
    }

    if (httpCode != 200) {
        Serial.printf("[LLMGW] Send message failed: HTTP %d\n", httpCode);
        return LLM_GW_ERR_CHAT_FAILED;
    }

    StaticJsonDocument<8192> doc;
    if (deserializeJson(doc, resp) != DeserializationError::Ok) {
        return LLM_GW_ERR_PARSE_ERROR;
    }

    const char* respText = doc["response"];
    if (respText) {
        response = String(respText);
    } else {
        response = "";
    }

    return LLM_GW_OK;
}

static LLMGWError llmGWStopChat() {
    if (strlen(llmGWSession.chatSessionId) == 0) {
        return LLM_GW_OK;
    }

    StaticJsonDocument<128> req;
    req["session_id"] = llmGWSession.chatSessionId;
    String body;
    serializeJson(req, body);

    int httpCode;
    llmGWHttpRequest("POST", "/chat/stop", body, httpCode);

    llmGWSession.chatSessionId[0] = '\0';
    llmGWSession.state = LLM_GW_STATE_READY;

    return LLM_GW_OK;
}

