static void bytesToHex(const uint8_t* bytes, size_t len, char* hex) {
    for (size_t i = 0; i < len; i++) {
        sprintf(hex + (i * 2), "%02x", bytes[i]);
    }
    hex[len * 2] = '\0';
}

static bool hexToBytes(const char* hex, uint8_t* bytes, size_t maxLen) {
    size_t hexLen = strlen(hex);
    if (hexLen % 2 != 0 || hexLen / 2 > maxLen) return false;

    for (size_t i = 0; i < hexLen; i += 2) {
        char byteStr[3] = { hex[i], hex[i + 1], '\0' };
        bytes[i / 2] = (uint8_t)strtol(byteStr, nullptr, 16);
    }
    return true;
}

